export const surahFrenchTitle = (n: number) => NAMES[n - 1]?.[1] ?? '';
export const surahTransliteration = (n: number) => NAMES[n - 1]?.[0] ?? '';

/** Applique les noms corrects à une sourate (et laisse le reste intact). */
export function withSurahNames<T extends Partial<Surah> | null | undefined>(s: T): T {
  if (!s || typeof s !== 'object') return s;
  const n = Number(s.number ?? s.id);
  const names = NAMES[n - 1];
  if (!names) return s;
  return { ...s, name_transliteration: names[0], name_french: names[1] };
}
